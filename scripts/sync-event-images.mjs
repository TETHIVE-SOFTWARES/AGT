/**
 * Scan public/img/events/<slug>/ and write data/event-images.generated.js.
 * Drop photos in a slug folder, then run: npm run sync:events
 */
import { readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const eventsDir = path.join(root, "public", "img", "events");
const outFile = path.join(root, "data", "event-images.generated.js");
const extensions = new Set([".webp", ".jpg", ".jpeg", ".png"]);

const entries = await readdir(eventsDir, { withFileTypes: true });
const slugs = entries
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort((a, b) => a.localeCompare(b));

/** @type {Record<string, { src: string, alt: string }[]>} */
const images = {};

for (const slug of slugs) {
  const files = await readdir(path.join(eventsDir, slug));
  const photos = files
    .filter((name) => extensions.has(path.extname(name).toLowerCase()))
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));

  images[slug] = photos.map((name, index) => ({
    src: `/img/events/${slug}/${name}`,
    alt: `Photograph ${String(index + 1).padStart(2, "0")}`,
  }));
}

const body = `/* Generated by scripts/sync-event-images.mjs. Do not edit by hand. */
export const eventImages = ${JSON.stringify(images, null, 2)};
`;

await writeFile(outFile, body);
console.log(`Wrote ${Object.keys(images).length} event folders to data/event-images.generated.js`);
